const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const read=p=>fs.readFileSync(path.join(__dirname,'..',...p.split('/')),'utf8');
const html=read('index.html');
assert.match(html,/id="codeToClaudeBtn"[^>]*onclick="codeSendToClaude\(\)"/,'Code tab needs the Send to Claude button');
const fn=html.slice(html.indexOf('async function codeSendToClaude('),html.indexOf('function toast('));
assert.ok(fn.length>50,'codeSendToClaude must exist');
assert.match(fn,/op:'sendToClaude'/,'the Code tab must call the native sendToClaude op');
assert.match(fn,/getElementById\('codeTask'\)/,'it must send the text typed in the Code tab');
assert.doesNotMatch(fn,/fetch\(|aiRequest/,'Send to Claude must never use a model provider or the network');
const app=read('ios/AIStudio/App.swift');
assert.match(app,/case "sendToClaude"/,'native bridge must answer sendToClaude');
assert.match(app,/utf8\.count <= 40_000/,'native bridge must cap the message size');
const tabs=read('ios/AIStudio/StudioTabController.swift');
assert.match(tabs,/func sendToClaude\(/,'tab controller must route the message to the Claude tab');
assert.match(tabs,/selectedIndex = 2/,'it must switch to the Claude tab');
const browser=read('ios/AIStudio/ClaudeBrowserController.swift');
assert.match(browser,/func insertIntoChat\(/,'Claude browser must type into the message box');
const insert=browser.slice(browser.indexOf('func insertIntoChat('),browser.indexOf('private func checkMemoryUpdate'));
assert.match(insert,/claudeInsertText/,'it must use the existing insert helper');
assert.match(insert,/UIPasteboard/,'it must fall back to the clipboard when the box is not found');
assert.doesNotMatch(insert,/click\(|submit|requestSubmit/i,'it must never press send for the person');
console.log('Claude bridge checks passed: Code tab text reaches the Claude message box, never auto-sent.');
